// '기타' 모양 세분화: 식약처 성상(CHART) 자연어에서 실제 모양 키워드를 추출.
// 모양 코드는 11종(원형~팔각형~반원형~기타)뿐이라, 하트·방패·눈사람 등은 전부 '기타'로
// 뭉친다. 성상 텍스트("…볼록한 심장형의 순백색…")에서 한 단계 더 좁혀 보조 표기한다.

// 우선순위 순서(구체적 특수형 먼저, 표준형 나중). 첫 일치 라벨을 사용.
const SHAPE_HINTS: [RegExp, string][] = [
  [/심장|하트/, '하트'],
  [/방패/, '방패'],
  [/눈사람/, '눈사람'],
  [/땅콩|누에/, '땅콩'],
  [/물방울|눈물/, '물방울'],
  [/오뚝이|오뚜기/, '오뚝이'],
  [/총알|탄환/, '총알'],
  [/초승달|반월|반달/, '반달'],
  [/화살/, '화살'],
  [/나비/, '나비'],
  [/도넛|도너츠|도우넛/, '도넛'],
  [/신장|콩팥/, '신장'],
  [/다이아몬드|다이아|다이야/, '다이아'],
  [/별\s*모양|별형/, '별'],
  // 성상이 표준 모양을 직접 적은 경우(코드가 '기타'여도)
  [/장방형/, '장방형'],
  [/타원형|타원/, '타원형'],
  [/마름모/, '마름모'],
  [/삼각/, '삼각형'],
  [/직사각|정사각|사각/, '사각형'],
  [/오각/, '오각형'],
  [/육각/, '육각형'],
  [/팔각/, '팔각형'],
  [/반원/, '반원형'],
  [/원형/, '원형'],
];

/** 성상 텍스트에서 모양 키워드 추출. 없으면 빈 문자열. */
export function refineShape(chart?: string): string {
  if (!chart) return '';
  for (const [re, label] of SHAPE_HINTS) if (re.test(chart)) return label;
  return '';
}

/**
 * 화면 표시용 모양 라벨.
 * - 표준 모양은 그대로
 * - '기타'면 성상에서 세분화해 "기타 · 심장형"처럼, 못 찾으면 "기타"
 */
export function shapeLabel(pill: { drugShape?: string; chart?: string }): string {
  const shape = (pill.drugShape || '').trim();
  if (shape !== '기타') return shape;
  const fine = refineShape(pill.chart);
  return fine ? `기타 · ${fine}` : '기타';
}
